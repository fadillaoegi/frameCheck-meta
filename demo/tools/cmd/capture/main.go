// Command capture renders demo/site/index.html once per case with headless
// Chrome and writes PNG fixtures plus a manifest whose ground-truth boxes are
// measured from the DOM, not drawn by hand.
//
//	go run ./cmd/capture                                          (dev set)
//	go run ./cmd/capture -cases cases-holdout.json -out fixtures-holdout
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"image"
	"image/jpeg"
	"image/png"
	"log"
	"math"
	"net/url"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/chromedp/cdproto/browser"
	"github.com/chromedp/chromedp"

	"framecheck/demo/tools/internal/fixtures"
)

func main() {
	demoDir := flag.String("demo", "..", "path to the demo/ directory")
	casesFile := flag.String("cases", "cases.json", "case list, relative to demo/")
	outName := flag.String("out", "fixtures", "output directory, relative to demo/")
	flag.Parse()
	if err := run(*demoDir, *casesFile, *outName); err != nil {
		log.Fatal(err)
	}
}

type rect struct{ X, Y, W, H float64 }

func run(demoDir, casesFile, outName string) error {
	demoDir, err := filepath.Abs(demoDir)
	if err != nil {
		return err
	}
	var list fixtures.CaseList
	if err := fixtures.ReadJSON(filepath.Join(demoDir, casesFile), &list); err != nil {
		return err
	}
	if list.Page == "" || strings.Contains(list.Page, "..") {
		return fmt.Errorf("%s: page must be a path inside demo/", casesFile)
	}
	pagePath := filepath.Join(demoDir, filepath.FromSlash(list.Page))
	page, err := os.ReadFile(pagePath)
	if err != nil {
		return err
	}
	outDir := filepath.Join(demoDir, outName)
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	ctx, cancel := chromedp.NewContext(context.Background())
	defer cancel()
	ctx, cancel = context.WithTimeout(ctx, 3*time.Minute)
	defer cancel()

	var product string
	if err := chromedp.Run(ctx, chromedp.ActionFunc(func(ctx context.Context) error {
		_, p, _, _, _, err := browser.GetVersion().Do(ctx)
		product = p
		return err
	})); err != nil {
		return err
	}

	c := list.Capture
	shoot := func(variant string, components []string) ([]byte, map[string]rect, error) {
		u := url.URL{Scheme: "file", Path: pagePath, RawQuery: "variant=" + url.QueryEscape(variant)}
		var buf []byte
		rects := map[string]rect{}
		actions := []chromedp.Action{
			chromedp.EmulateViewport(int64(c.ViewportWidthCSS), int64(c.ViewportHeightCSS), chromedp.EmulateScale(c.DevicePixelRatio)),
			chromedp.Navigate(u.String()),
			chromedp.WaitReady("body", chromedp.ByQuery),
		}
		for _, comp := range components {
			comp := comp
			actions = append(actions, chromedp.ActionFunc(func(ctx context.Context) error {
				var r rect
				js := fmt.Sprintf(`(() => { const e = document.querySelector('[data-fc=%q]');
					if (!e) return null; const b = e.getBoundingClientRect();
					return {X: b.x, Y: b.y, W: b.width, H: b.height}; })()`, comp)
				if err := chromedp.Evaluate(js, &r).Do(ctx); err != nil {
					return fmt.Errorf("measure %s: %w", comp, err)
				}
				if r.W <= 0 || r.H <= 0 {
					return fmt.Errorf("component %s not found or empty in variant %s", comp, variant)
				}
				rects[comp] = r
				return nil
			}))
		}
		actions = append(actions, chromedp.CaptureScreenshot(&buf))
		if err := chromedp.Run(ctx, actions...); err != nil {
			return nil, nil, err
		}
		return buf, rects, nil
	}

	var allComponents []string
	for _, cs := range list.Cases {
		if cs.Component != nil {
			allComponents = append(allComponents, *cs.Component)
		}
	}
	refPNG, refRects, err := shoot("reference", allComponents)
	if err != nil {
		return err
	}
	again, _, err := shoot("reference", nil)
	if err != nil {
		return err
	}
	deterministic := bytes.Equal(refPNG, again)
	if !deterministic {
		log.Println("WARNING: two captures of the reference differ; fixtures are not byte-deterministic")
	}

	refImg, err := writeImage(outDir, "reference.png", refPNG)
	if err != nil {
		return err
	}
	scale := c.DevicePixelRatio
	toBox := func(r rect, w, h int) *fixtures.Box {
		// Round outward so the labelled region covers the whole component.
		x0 := clamp(int(math.Floor(r.X*scale)), 0, w)
		y0 := clamp(int(math.Floor(r.Y*scale)), 0, h)
		x1 := clamp(int(math.Ceil((r.X+r.W)*scale)), 0, w)
		y1 := clamp(int(math.Ceil((r.Y+r.H)*scale)), 0, h)
		return &fixtures.Box{X: x0, Y: y0, Width: x1 - x0, Height: y1 - y0}
	}

	m := fixtures.Manifest{
		Origin:        "fixture",
		About:         "Generated by demo/tools/cmd/capture from demo/cases.json. Synthetic, self-owned page. Not model output.",
		GeneratedAt:   time.Now().UTC().Format(time.RFC3339),
		Page:          list.Page,
		PageSHA256:    sha(page),
		Browser:       product,
		Capture:       c,
		Reference:     refImg,
		Deterministic: deterministic,
	}

	for _, cs := range list.Cases {
		var comps []string
		if cs.Component != nil {
			comps = []string{*cs.Component}
		}
		actPNG, actRects, err := shoot(cs.Variant, comps)
		if err != nil {
			return fmt.Errorf("case %s: %w", cs.ID, err)
		}
		name := "actual-" + cs.ID + ".png"
		switch cs.Postprocess {
		case "":
		case "jpeg85":
			if cs.Category != nil {
				return fmt.Errorf("case %s: postprocess is only for controls", cs.ID)
			}
			if actPNG, err = toJPEG(actPNG, 85); err != nil {
				return err
			}
			name = "actual-" + cs.ID + ".jpg"
		default:
			return fmt.Errorf("case %s: unknown postprocess %q", cs.ID, cs.Postprocess)
		}
		actImg, err := writeImage(outDir, name, actPNG)
		if err != nil {
			return err
		}
		mc := fixtures.ManifestCase{Case: cs, Actual: actImg, Expected: []fixtures.Expected{}}
		if cs.Category != nil && cs.Component != nil {
			if cs.Variant != "reference" && actImg.SHA256 == refImg.SHA256 {
				return fmt.Errorf("case %s: defect variant renders identically to the reference", cs.ID)
			}
			e := fixtures.Expected{Category: *cs.Category, Component: *cs.Component,
				ReferenceBox: toBox(refRects[*cs.Component], refImg.Width, refImg.Height)}
			if *cs.Category != "missing_element" {
				e.ActualBox = toBox(actRects[*cs.Component], actImg.Width, actImg.Height)
			}
			if err := checkDiffContained(refPNG, actPNG, e); err != nil {
				return fmt.Errorf("case %s: %w", cs.ID, err)
			}
			mc.Expected = append(mc.Expected, e)
		} else if cs.Postprocess == "" && actImg.SHA256 != refImg.SHA256 && deterministic {
			return fmt.Errorf("control %s differs from the reference", cs.ID)
		}
		m.Cases = append(m.Cases, mc)
		log.Printf("captured %-22s %s", cs.ID, actImg.SHA256[:12])
	}
	return fixtures.WriteJSON(filepath.Join(outDir, "manifest.json"), m)
}

func toJPEG(pngData []byte, quality int) ([]byte, error) {
	img, err := png.Decode(bytes.NewReader(pngData))
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := jpeg.Encode(&buf, img, &jpeg.Options{Quality: quality}); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func writeImage(dir, name string, data []byte) (fixtures.Image, error) {
	cfg, _, err := image.DecodeConfig(bytes.NewReader(data))
	if err != nil {
		return fixtures.Image{}, errors.New("capture is not a PNG or JPEG")
	}
	if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
		return fixtures.Image{}, err
	}
	return fixtures.Image{File: name, SHA256: sha(data), Width: cfg.Width, Height: cfg.Height}, nil
}

// checkDiffContained fails when pixels change outside the labelled boxes,
// which would mean the defect leaks into other components and confounds the case.
func checkDiffContained(refPNG, actPNG []byte, e fixtures.Expected) error {
	ref, err := png.Decode(bytes.NewReader(refPNG))
	if err != nil {
		return err
	}
	act, err := png.Decode(bytes.NewReader(actPNG))
	if err != nil {
		return err
	}
	const margin = 2
	inside := func(x, y int) bool {
		for _, b := range []*fixtures.Box{e.ReferenceBox, e.ActualBox} {
			if b != nil && x >= b.X-margin && x < b.X+b.Width+margin && y >= b.Y-margin && y < b.Y+b.Height+margin {
				return true
			}
		}
		return false
	}
	bounds := ref.Bounds()
	outside := 0
	for y := bounds.Min.Y; y < bounds.Max.Y; y++ {
		for x := bounds.Min.X; x < bounds.Max.X; x++ {
			r1, g1, b1, _ := ref.At(x, y).RGBA()
			r2, g2, b2, _ := act.At(x, y).RGBA()
			if (r1 != r2 || g1 != g2 || b1 != b2) && !inside(x, y) {
				outside++
			}
		}
	}
	if outside > 0 {
		return fmt.Errorf("%d pixels changed outside the labelled %s boxes", outside, e.Component)
	}
	return nil
}

func sha(b []byte) string {
	s := sha256.Sum256(b)
	return hex.EncodeToString(s[:])
}

func clamp(v, lo, hi int) int { return max(lo, min(v, hi)) }
