// Package fixtures defines the case list and the generated fixture manifest.
package fixtures

import (
	"encoding/json"
	"fmt"
	"os"
)

type Capture struct {
	ViewportWidthCSS  int     `json:"viewport_width_css"`
	ViewportHeightCSS int     `json:"viewport_height_css"`
	DevicePixelRatio  float64 `json:"device_pixel_ratio"`
	ContentStateKey   string  `json:"content_state_key"`
}

// Case is one hand-written entry in demo/cases.json.
type Case struct {
	ID        string  `json:"id"`
	Variant   string  `json:"variant"`
	Split     string  `json:"split"`
	Category  *string `json:"category"`
	Component *string `json:"component"`
	Decidable bool    `json:"decidable"`
	Note      string  `json:"note,omitempty"`
	// Postprocess re-encodes the actual capture, e.g. "jpeg85" for a
	// compression-noise control.
	Postprocess string `json:"postprocess,omitempty"`
}

type CaseList struct {
	About   string  `json:"about"`
	Page    string  `json:"page"`
	Capture Capture `json:"capture"`
	Cases   []Case  `json:"cases"`
}

// Box is in original raster pixels, origin top left.
type Box struct {
	X      int `json:"x"`
	Y      int `json:"y"`
	Width  int `json:"width"`
	Height int `json:"height"`
}

func (b Box) IoU(o Box) float64 {
	x0, y0 := max(b.X, o.X), max(b.Y, o.Y)
	x1, y1 := min(b.X+b.Width, o.X+o.Width), min(b.Y+b.Height, o.Y+o.Height)
	if x1 <= x0 || y1 <= y0 {
		return 0
	}
	inter := float64((x1 - x0) * (y1 - y0))
	union := float64(b.Width*b.Height+o.Width*o.Height) - inter
	return inter / union
}

type Expected struct {
	Category     string `json:"category"`
	Component    string `json:"component"`
	ReferenceBox *Box   `json:"reference_box"`
	ActualBox    *Box   `json:"actual_box"`
}

// MatchBox is the labelled region a finding must overlap: the reference box
// for a missing element (it has no actual location), otherwise the actual box.
func (e Expected) MatchBox() *Box {
	if e.Category == "missing_element" {
		return e.ReferenceBox
	}
	return e.ActualBox
}

type Image struct {
	File   string `json:"file"`
	SHA256 string `json:"sha256"`
	Width  int    `json:"width"`
	Height int    `json:"height"`
}

type ManifestCase struct {
	Case
	Actual   Image      `json:"actual"`
	Expected []Expected `json:"expected"`
}

// Manifest is generated by cmd/capture. Origin is always "fixture".
type Manifest struct {
	Origin        string         `json:"origin"`
	About         string         `json:"about"`
	GeneratedAt   string         `json:"generated_at"`
	Page          string         `json:"page"`
	PageSHA256    string         `json:"page_sha256"`
	Browser       string         `json:"browser"`
	Capture       Capture        `json:"capture"`
	Reference     Image          `json:"reference"`
	Deterministic bool           `json:"deterministic"`
	Cases         []ManifestCase `json:"cases"`
}

func ReadJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(b, v); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return nil
}

func WriteJSON(path string, v any) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(b, '\n'), 0o644)
}
